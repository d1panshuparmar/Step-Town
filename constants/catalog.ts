function recipe(
  id: string,
  input: ItemId,
  inputQty: number,
  output: ItemId,
  outputQty: number,
  processMs: number,
  input2?: ItemId,
  input2Qty?: number
): FactoryRecipe {
  const r: FactoryRecipe = { id, input, inputQty, output, outputQty, processMs };
  if (input2 && input2Qty) {
    r.input2 = input2;
    r.input2Qty = input2Qty;
  }
  return r;
}

