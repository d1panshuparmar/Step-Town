export function factoryRecipes(def: BuildingDef): FactoryRecipe[] {
  if (def.recipes?.length) return def.recipes;
  if (def.recipe) {
    return [
      {
        id: def.recipe.output,
        ...def.recipe,
      },
    ];
  }
  return [];
}

